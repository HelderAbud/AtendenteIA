import psycopg


class FilaPostgres:
    def __init__(self, url: str) -> None:
        self._url = url
        with self._conectar() as conexao:
            conexao.execute(
                """
                CREATE TABLE IF NOT EXISTS encaminhamentos (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    pergunta TEXT NOT NULL,
                    fluxo TEXT NOT NULL,
                    resumo TEXT
                )
                """
            )
            conexao.commit()

    def _conectar(self) -> psycopg.Connection:
        return psycopg.connect(self._url)

    def registrar(self, pergunta: str, fluxo: str, resumo: str | None) -> None:
        with self._conectar() as conexao:
            conexao.execute(
                "INSERT INTO encaminhamentos (pergunta, fluxo, resumo) VALUES (%s, %s, %s)",
                (pergunta, fluxo, resumo),
            )
            conexao.commit()

    def listar(self) -> list[dict]:
        with self._conectar() as conexao:
            linhas = conexao.execute(
                "SELECT id, pergunta, fluxo, resumo FROM encaminhamentos ORDER BY id"
            ).fetchall()
        return [
            {"id": linha[0], "pergunta": linha[1], "fluxo": linha[2], "resumo": linha[3]}
            for linha in linhas
        ]

    def remover(self, item_id: int) -> None:
        with self._conectar() as conexao:
            cursor = conexao.execute(
                "DELETE FROM encaminhamentos WHERE id = %s", (item_id,)
            )
            conexao.commit()
            if cursor.rowcount == 0:
                raise KeyError(item_id)
